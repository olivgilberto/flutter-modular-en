import 'dart:math';

/// A version 4 UUID (RFC 9562): 122 random bits from `Random.secure()`,
/// with the version and variant bits in place. Ten lines instead of one
/// more dependency. It is the id of the tasks, generated on the device, and
/// of the outbox operations (chapter 31).
String newUuidV4([Random? random]) {
  final source = random ?? Random.secure();
  final bytes = List<int>.generate(16, (_) => source.nextInt(256));
  bytes[6] = (bytes[6] & 0x0f) | 0x40; // version 4
  bytes[8] = (bytes[8] & 0x3f) | 0x80; // variant 10xx
  final hex = [
    for (final byte in bytes) byte.toRadixString(16).padLeft(2, '0'),
  ].join();
  return '${hex.substring(0, 8)}-${hex.substring(8, 12)}-'
      '${hex.substring(12, 16)}-${hex.substring(16, 20)}-${hex.substring(20)}';
}
