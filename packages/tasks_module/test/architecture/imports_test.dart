/// What the tasks module imports, read from its own files (chapter 36).
/// `check-deps` checks the `pubspec.yaml`, and
/// `depend_on_referenced_packages` stops importing what it does not declare;
/// this test checks what each layer uses of what was declared. The analyzer
/// plugin in chapter 40 generalizes the rules to every module.
void main() {
  final files = _sources();

  test('reads the module\'s files', () {
    expect(files.keys, contains('tasks_module.dart'));
    expect(files.length, greaterThan(30));
  });

  test('each layer imports only the packages that belong to it', () {
    const allowed = {
      'domain': {'core'},
      // Chapter 38: the use case receives AppAnalytics, a core port.
      'application': {'core'},
      'adapters/driven': {'core'},
      // Chapter 37: the translations. The class generated by gen-l10n imports
      // flutter_localizations and intl, and lives on the driving side.
      'adapters/driving': {
        'core',
        'design_system',
        'flutter',
        'flutter_bloc',
        'bloc_concurrency',
        'go_router',
        'get_it',
        'flutter_localizations',
        'intl',
      },
      'entry': {'core', 'get_it'},
    };
    final found = <String>[];
    files.forEach((path, imports) {
      final layer = _layerOf(path);
      for (final uri in imports.where((u) => u.startsWith('package:'))) {
        final package = uri.substring('package:'.length).split('/').first;
        if (!allowed[layer]!.contains(package)) found.add('$path → $uri');
      }
    });
    expect(found, isEmpty);
  });

  test('no technology the core abstracts, no other module, no '
      'adapter', () {
    final everything = files.values.expand((imports) => imports).toSet();
    final forbidden = everything.where(
      (uri) =>
          uri.startsWith('package:auth_module/') ||
          uri.startsWith('package:adapter_') ||
          uri.startsWith('package:dio/') ||
          uri.startsWith('package:sqflite') ||
          uri.startsWith('package:flutter_secure_storage/') ||
          uri.startsWith('package:path_provider/') ||
          uri.startsWith('package:workmanager/') ||
          uri.startsWith('package:shared_preferences/') ||
          uri.startsWith('package:connectivity_plus/') ||
          uri.startsWith('package:firebase_') ||
          uri.startsWith('package:http/'),
    );
    expect(forbidden, isEmpty);
  });

  test('the domain and the application know neither Flutter nor dart:io', () {
    final found = [
      for (final MapEntry(key: path, value: imports) in files.entries)
        if (_layerOf(path) == 'domain' || _layerOf(path) == 'application')
          for (final uri in imports)
            if (uri.startsWith('package:flutter') || uri == 'dart:io')
              '$path → $uri',
    ];
    expect(found, isEmpty);
  });

  test('the layers point inward, and the two sides do not see each other', () {
    // Who each layer may import inside its own module.
    const inward = {
      'domain': {'domain'},
      'application': {'domain', 'application'},
      'adapters/driven': {'domain', 'application', 'adapters/driven'},
      'adapters/driving': {'domain', 'application', 'adapters/driving'},
      'entry': {'domain', 'application', 'adapters/driven', 'adapters/driving'},
    };
    final found = <String>[];
    files.forEach((path, imports) {
      final from = _layerOf(path);
      for (final uri in imports.where((u) => !u.contains(':'))) {
        final target = _layerOf(_resolve(path, uri));
        if (!inward[from]!.contains(target)) found.add('$path → $uri');
      }
    });
    expect(found, isEmpty);
  });

  test('get_it only appears at the edge: the entry file and the '
      'Pages', () {
    final found = [
      for (final MapEntry(key: path, value: imports) in files.entries)
        if (imports.contains('package:get_it/get_it.dart') &&
            path != 'tasks_module.dart' &&
            !path.startsWith('adapters/driving/pages/'))
          path,
    ];
    expect(found, isEmpty);
  });
}

/// Each file in lib/, by relative path, with the imports, exports, and
/// parts it declares.
Map<String, List<String>> _sources() {
  final root = Directory('lib');
  // The directive line is enough: a `show` on the next line does not change the target.
  final directive = RegExp(r"^(?:import|export|part)\s+'([^']+)'");
  return {
    for (final file in root.listSync(recursive: true).whereType<File>())
      if (file.path.endsWith('.dart'))
        file.path.substring('lib/'.length).replaceAll(r'\', '/'): [
          for (final line in file.readAsLinesSync())
            if (directive.firstMatch(line.trim()) case final match?)
              match.group(1)!,
        ],
  };
}

String _layerOf(String path) {
  for (final layer in [
    'domain',
    'application',
    'adapters/driven',
    'adapters/driving',
  ]) {
    if (path.startsWith('$layer/')) return layer;
  }
  return 'entry';
}

/// The path, relative to lib/, of a relative import.
String _resolve(String from, String uri) {
  final parts = from.split('/')..removeLast();
  for (final segment in uri.split('/')) {
    if (segment == '..') {
      parts.removeLast();
    } else if (segment != '.') {
      parts.add(segment);
    }
  }
  return parts.join('/');
}
